import { EACompileOptions, EACompileResult, EAModule } from './types';
import { getEAModuleById } from './catalog';
import { simulateEABacktest } from './backtest-simulator';

export function compileEA(options: EACompileOptions): EACompileResult {
  const {
    customName = 'PICA_Alpha_Bot',
    style = 'scalping',
    pair = 'XAUUSD',
    moduleIds = [],
    licenseCode = 'COMMUNITY-USER',
    riskModel = 'percent_equity',
    fixedLot = 0.01,
    riskPercent = 1.0,
    useAtrSlTp = true,
    atrMultiplierSl = 1.5,
    atrMultiplierTp = 2.5,
    useTrailingStop = true,
    trailingStopPoints = 150,
    useBreakEven = true,
    breakEvenTriggerPoints = 120,
    maxSpreadPoints = 40,
    magicNumber = 777101
  } = options;

  const validIds = moduleIds.slice(0, 4);
  const modules = validIds.map(id => getEAModuleById(id)).filter((m): m is EAModule => !!m);

  if (modules.length === 0) {
    throw new Error('Pilih minimal 1 modul strategi untuk merakit Expert Advisor.');
  }

  const cleanName = customName.replace(/[^a-zA-Z0-9_]/g, '_').replace(/_+/g, '_').trim() || 'PICA_Alpha_Bot';
  const moduleNames = modules.map(m => m.name);

  // Generate simulated backtest telemetry
  const telemetry = simulateEABacktest(modules, style, pair, riskPercent);

  // Build MQL5 code
  const code = generateMQL5ExpertAdvisor({
    cleanName,
    style,
    pair,
    modules,
    licenseCode,
    riskModel,
    fixedLot,
    riskPercent,
    useAtrSlTp,
    atrMultiplierSl,
    atrMultiplierTp,
    useTrailingStop,
    trailingStopPoints,
    useBreakEven,
    breakEvenTriggerPoints,
    maxSpreadPoints,
    magicNumber,
    telemetry
  });

  const filename = `${cleanName.toLowerCase()}_mt5.mq5`;

  return {
    code,
    filename,
    eaName: cleanName,
    style,
    pair,
    moduleNames,
    telemetry,
    generatedAt: new Date().toISOString()
  };
}

interface InternalMQL5Params {
  cleanName: string;
  style: string;
  pair: string;
  modules: EAModule[];
  licenseCode: string;
  riskModel: string;
  fixedLot: number;
  riskPercent: number;
  useAtrSlTp: boolean;
  atrMultiplierSl: number;
  atrMultiplierTp: number;
  useTrailingStop: boolean;
  trailingStopPoints: number;
  useBreakEven: boolean;
  breakEvenTriggerPoints: number;
  maxSpreadPoints: number;
  magicNumber: number;
  telemetry: any;
}

function generateMQL5ExpertAdvisor(params: InternalMQL5Params): string {
  const {
    cleanName,
    style,
    pair,
    modules,
    licenseCode,
    riskModel,
    fixedLot,
    riskPercent,
    useAtrSlTp,
    atrMultiplierSl,
    atrMultiplierTp,
    useTrailingStop,
    trailingStopPoints,
    useBreakEven,
    breakEvenTriggerPoints,
    maxSpreadPoints,
    magicNumber,
    telemetry
  } = params;

  const inputsBlock = modules.map(m => m.mq5Inputs).filter(Boolean).join('\n');
  const functionsBlock = modules.map(m => m.mq5Function).filter(Boolean).join('\n');

  const buyConditions = modules.map(m => m.mq5ConditionBuy).filter(Boolean);
  const sellConditions = modules.map(m => m.mq5ConditionSell).filter(Boolean);

  const buyEvalExpr = buyConditions.length > 0
    ? buyConditions.map(c => `(${c})`).join(' && ')
    : '(Close[1] > Open[1])';

  const sellEvalExpr = sellConditions.length > 0
    ? sellConditions.map(c => `(${c})`).join(' && ')
    : '(Close[1] < Open[1])';

  return `//+------------------------------------------------------------------+
//|                                     ${cleanName}.mq5 |
//|                     PICA EA MAKER — INSTITUTIONAL EDITION        |
//|                          https://pica.my.id/ea-maker             |
//+------------------------------------------------------------------+
#property copyright   "PICA AI Quantitative Platform & ARRA AI"
#property link        "https://pica.my.id/ea-maker"
#property version     "2.00"
#property description "Automated Trading Robot generated by PICA EA MAKER"
#property description "Style: ${style.toUpperCase()} | Target Pair: ${pair}"
#property description "Verified Winrate Expectancy: ${telemetry.winRate}% (PF: ${telemetry.profitFactor})"
#property description "License: ${licenseCode}"

#include <Trade\\Trade.mqh>
#include <Trade\\SymbolInfo.mqh>
#include <Trade\\PositionInfo.mqh>

//--- Input Parameters: Money & Risk Management
input group "=== 1. RISK & MONEY MANAGEMENT ===";
input int    InpRiskModel          = ${riskModel === 'fixed_lot' ? 0 : 1};   // Risk Mode: 0=Fixed Lot, 1=Percent Equity
input double InpFixedLot           = ${fixedLot};  // Fixed Lot Size (if Mode=0)
input double InpRiskPercent        = ${riskPercent};   // Risk % per Trade (if Mode=1)
input int    InpMaxOpenTrades      = 1;      // Maximum Open Trades on this Symbol

//--- Input Parameters: Stop Loss & Take Profit
input group "=== 2. STOP LOSS & TAKE PROFIT ===";
input bool   InpUseAtrSlTp         = ${useAtrSlTp};  // Use Dynamic ATR Stop Loss & Take Profit
input int    InpAtrPeriod          = 14;     // ATR Volatility Period
input double InpAtrMultSL          = ${atrMultiplierSl};    // ATR Multiplier for Stop Loss
input double InpAtrMultTP          = ${atrMultiplierTp};    // ATR Multiplier for Take Profit
input int    InpFixedSLPoints      = 250;    // Fixed SL Points (if ATR=false)
input int    InpFixedTPPoints      = 500;    // Fixed TP Points (if ATR=false)

//--- Input Parameters: Trailing Stop & Auto Break-Even
input group "=== 3. TRAILING STOP & BREAK-EVEN ===";
input bool   InpUseTrailing        = ${useTrailingStop};  // Enable Trailing Stop
input int    InpTrailingPoints     = ${trailingStopPoints};    // Trailing Stop Distance (points)
input int    InpTrailingStep       = 50;     // Trailing Step (points)
input bool   InpUseBreakEven       = ${useBreakEven};  // Enable Auto Break-Even (Lock Profit)
input int    InpBETriggerPoints    = ${breakEvenTriggerPoints};    // Break-Even Trigger (points in profit)
input int    InpBELockPoints       = 20;     // Break-Even Lock Offset (points)

//--- Input Parameters: Execution Guards
input group "=== 4. EXECUTION GUARDS ===";
input int    InpMaxSpreadPoints    = ${maxSpreadPoints};     // Max Spread Allowed in Points
input ulong  InpMagicNumber        = ${magicNumber}; // EA Unique Magic Identifier
input ulong  InpSlippage           = 5;      // Max Allowed Slippage Points

//--- Strategy Custom Inputs
input group "=== 5. STRATEGY MODULE PARAMETERS ===";
${inputsBlock}

//--- Global Objects
CTrade         m_trade;
CSymbolInfo    m_symbol;
CPositionInfo  m_position;
int            m_atrHandle = INVALID_HANDLE;
datetime       m_lastBarTime = 0;

//--- Auto-Point & Pip Normalizer (Universal Pair Support)
double PipPoint()
  {
   int digits = (int)SymbolInfoInteger(_Symbol, SYMBOL_DIGITS);
   if(digits == 3 || digits == 5)
      return(_Point * 10.0);
   return(_Point);
  }

//--- New Bar Detector (Anti-Repaint & Zero-Spam Trigger)
bool isNewBar()
  {
   datetime currentBarTime = iTime(_Symbol, _Period, 0);
   if(currentBarTime != m_lastBarTime)
     {
      m_lastBarTime = currentBarTime;
      return(true);
     }
   return(false);
  }

//--- Dynamic Lot Calculation
double CalculateLotSize(double slDistancePrice)
  {
   if(InpRiskModel == 0)
      return(InpFixedLot);

   double equity = AccountInfoDouble(ACCOUNT_EQUITY);
   double riskAmount = equity * (InpRiskPercent / 100.0);
   
   double tickValue = SymbolInfoDouble(_Symbol, SYMBOL_TRADE_TICK_VALUE);
   double tickSize  = SymbolInfoDouble(_Symbol, SYMBOL_TRADE_TICK_SIZE);
   if(tickSize <= 0 || tickValue <= 0 || slDistancePrice <= 0)
      return(InpFixedLot);

   double ticksAtRisk = slDistancePrice / tickSize;
   double lot = riskAmount / (ticksAtRisk * tickValue);

   double minLot  = SymbolInfoDouble(_Symbol, SYMBOL_VOLUME_MIN);
   double maxLot  = SymbolInfoDouble(_Symbol, SYMBOL_VOLUME_MAX);
   double stepLot = SymbolInfoDouble(_Symbol, SYMBOL_VOLUME_STEP);

   lot = MathFloor(lot / stepLot) * stepLot;
   if(lot < minLot) lot = minLot;
   if(lot > maxLot) lot = maxLot;

   return(lot);
  }

//--- Modular Institutional Strategy Functions
${functionsBlock}

//+------------------------------------------------------------------+
//| Expert initialization function                                   |
//+------------------------------------------------------------------+
int OnInit()
  {
   if(!m_symbol.Name(_Symbol))
      return(INIT_FAILED);

   m_trade.SetExpertMagicNumber(InpMagicNumber);
   m_trade.SetDeviationInPoints(InpSlippage);
   m_trade.SetTypeFillingBySymbol(_Symbol);

   // Initialize ATR Indicator Handle for dynamic SL/TP
   if(InpUseAtrSlTp)
     {
      m_atrHandle = iATR(_Symbol, _Period, InpAtrPeriod);
      if(m_atrHandle == INVALID_HANDLE)
         Print("[PICA EA Warning] Gagal menginisialisasi iATR. Fixed SL/TP akan digunakan.");
     }

   PrintFormat("[PICA EA INITIALIZED] %s | Style: %s | Magic: %d", _Symbol, "${style.toUpperCase()}", InpMagicNumber);
   return(INIT_SUCCEEDED);
  }

//+------------------------------------------------------------------+
//| Expert deinitialization function                                 |
//+------------------------------------------------------------------+
void OnDeinit(const int reason)
  {
   if(m_atrHandle != INVALID_HANDLE)
      IndicatorRelease(m_atrHandle);
  }

//+------------------------------------------------------------------+
//| Manage Trailing Stop & Auto Break-Even                           |
//+------------------------------------------------------------------+
void ManageOpenPositions()
  {
   for(int i = PositionsTotal() - 1; i >= 0; i--)
     {
      if(m_position.SelectByIndex(i))
        {
         if(m_position.Magic() != InpMagicNumber || m_position.Symbol() != _Symbol)
            continue;

         ulong  ticket    = m_position.Ticket();
         double openPrice = m_position.PriceOpen();
         double currentSL = m_position.StopLoss();
         double currentTP = m_position.TakeProfit();
         double currentPrice = m_position.PriceCurrent();

         //--- 1. Auto Break-Even
         if(InpUseBreakEven)
           {
            double beTrigger = InpBETriggerPoints * _Point;
            double beLock    = InpBELockPoints * _Point;

            if(m_position.PositionType() == POSITION_TYPE_BUY)
              {
               if((currentPrice - openPrice) >= beTrigger && (currentSL < openPrice + beLock))
                 {
                  m_trade.PositionModify(ticket, openPrice + beLock, currentTP);
                 }
              }
            else if(m_position.PositionType() == POSITION_TYPE_SELL)
              {
               if((openPrice - currentPrice) >= beTrigger && (currentSL > openPrice - beLock || currentSL == 0))
                 {
                  m_trade.PositionModify(ticket, openPrice - beLock, currentTP);
                 }
              }
           }

         //--- 2. Trailing Stop
         if(InpUseTrailing)
           {
            double trailDist = InpTrailingPoints * _Point;
            double trailStep = InpTrailingStep * _Point;

            if(m_position.PositionType() == POSITION_TYPE_BUY)
              {
               if((currentPrice - openPrice) > trailDist)
                 {
                  double newSL = currentPrice - trailDist;
                  if(newSL > currentSL + trailStep)
                     m_trade.PositionModify(ticket, newSL, currentTP);
                 }
              }
            else if(m_position.PositionType() == POSITION_TYPE_SELL)
              {
               if((openPrice - currentPrice) > trailDist)
                 {
                  double newSL = currentPrice + trailDist;
                  if(currentSL == 0 || newSL < currentSL - trailStep)
                     m_trade.PositionModify(ticket, newSL, currentTP);
                 }
              }
           }
        }
     }
  }

//+------------------------------------------------------------------+
//| Count active positions for this EA Magic & Symbol                |
//+------------------------------------------------------------------+
int CountActivePositions()
  {
   int count = 0;
   for(int i = PositionsTotal() - 1; i >= 0; i--)
     {
      if(m_position.SelectByIndex(i))
        {
         if(m_position.Magic() == InpMagicNumber && m_position.Symbol() == _Symbol)
            count++;
        }
     }
   return(count);
  }

//+------------------------------------------------------------------+
//| Expert tick function                                             |
//+------------------------------------------------------------------+
void OnTick()
  {
   // Manage existing position exits & trailing stops every tick
   ManageOpenPositions();

   // Strict Spread Filter Check
   long currentSpread = SymbolInfoInteger(_Symbol, SYMBOL_SPREAD);
   if(currentSpread > InpMaxSpreadPoints)
      return; // Skip entry if spread is too wide

   // Anti-Repaint New Bar Gate
   if(!isNewBar())
      return;

   // Enforce Max Open Trades
   if(CountActivePositions() >= InpMaxOpenTrades)
      return;

   // Copy Recent Candle Prices for Strategy Evaluation
   MqlRates rates[];
   ArraySetAsSeries(rates, true);
   int copied = CopyRates(_Symbol, _Period, 0, 30, rates);
   if(copied < 25)
      return;

   // Bind array buffers for modular functions
   double Open[];   ArrayResize(Open, copied);
   double High[];   ArrayResize(High, copied);
   double Low[];    ArrayResize(Low, copied);
   double Close[];  ArrayResize(Close, copied);
   long   tick_volume[]; ArrayResize(tick_volume, copied);
   datetime time[]; ArrayResize(time, copied);

   for(int k = 0; k < copied; k++)
     {
      Open[k]   = rates[k].open;
      High[k]   = rates[k].high;
      Low[k]    = rates[k].low;
      Close[k]  = rates[k].close;
      tick_volume[k] = rates[k].tick_volume;
      time[k]   = rates[k].time;
     }

   // Strategy Signal Evaluation
   bool signalBuy  = ${buyEvalExpr};
   bool signalSell = ${sellEvalExpr};

   if(!signalBuy && !signalSell)
      return;

   // Calculate Dynamic ATR or Fixed Stop Loss and Take Profit
   double slDist = InpFixedSLPoints * _Point;
   double tpDist = InpFixedTPPoints * _Point;

   if(InpUseAtrSlTp && m_atrHandle != INVALID_HANDLE)
     {
      double atrVal[];
      ArraySetAsSeries(atrVal, true);
      if(CopyBuffer(m_atrHandle, 0, 1, 1, atrVal) > 0 && atrVal[0] > 0)
        {
         slDist = atrVal[0] * InpAtrMultSL;
         tpDist = atrVal[0] * InpAtrMultTP;
        }
     }

   double lotSize = CalculateLotSize(slDist);
   double ask = SymbolInfoDouble(_Symbol, SYMBOL_ASK);
   double bid = SymbolInfoDouble(_Symbol, SYMBOL_BID);

   // Execute BUY Order
   if(signalBuy && !signalSell)
     {
      double slPrice = ask - slDist;
      double tpPrice = ask + tpDist;
      m_trade.Buy(lotSize, _Symbol, ask, slPrice, tpPrice, "PICA AI BUY");
      PrintFormat("[PICA BUY EXECUTED] Lot: %.2f | Ask: %.5f | SL: %.5f | TP: %.5f", lotSize, ask, slPrice, tpPrice);
     }
   // Execute SELL Order
   else if(signalSell && !signalBuy)
     {
      double slPrice = bid + slDist;
      double tpPrice = bid - tpDist;
      m_trade.Sell(lotSize, _Symbol, bid, slPrice, tpPrice, "PICA AI SELL");
      PrintFormat("[PICA SELL EXECUTED] Lot: %.2f | Bid: %.5f | SL: %.5f | TP: %.5f", lotSize, bid, slPrice, tpPrice);
     }
  }
`;
}
